#!/usr/bin/env python3
"""
exp2_latency.py -- Experiment 2: inference latency of AOTInductor vs SOL, both
executed through vAccel, per model and execution target.

Computation time only (no network, no pre/post-processing), median and 25th /
75th percentile (iqr_low/high_ms) per model, execution target and compiler:
  Local CPU  inference_ms of the local robot runs (common.LOCAL_RUN_TAG,
             backend vaccel-local-{sol,ptc})
  Edge CPU   computation per call profiled inside the vAccel agent during the
  Edge GPU   remote runs (common.agent_computation; SOL: sol_predict, PyTorch:
             torch_predict + torch_out of the eval-patched plugin -- same scope)

Figure: rows = execution target, columns = task; 2 bars per model -- "vAccel + PyTorch"
(AOTInductor) and "vAccSOL" -- with IQR error bars; y axis "Computation time (ms)",
linear per panel.

LaTeX table (exp2-latency.tex, single column): the medians of exp2-latency.csv (1 decimal), PyTorch and
SOL per execution target. The CSV's sol_speedup (PyTorch / SOL, from the unrounded medians: the printed
1-decimal values distort the ratio at a few ms) is for the text.

Usage:    python3 exp2_latency.py
Produces: exp2-latency.{csv,pdf,tex}
"""
import statistics

import matplotlib.pyplot as plt
from matplotlib.ticker import MaxNLocator

from common import (COMPILERS, EDGE_COLOR, HERE, LEGEND_STYLE, MODEL_NAME, TARGETS, TEX_COLOUR, TEX_INDENT, TEX_MODEL, TEX_TASK, TITLES,
                    agent_computation, apply_theme, model_of, model_ticks, patches, read_rows, save, style_axes,
                    target_runs, write_rows)

CSV, PDF, TEX = HERE / "exp2-latency.csv", HERE / "exp2-latency.pdf", HERE / "exp2-latency.tex"
COLUMNS = ["category", "model", "execution_target", "compiler", "inference_ms", "iqr_low_ms", "iqr_high_ms",
           "sol_speedup"]  # SOL rows: PyTorch median / SOL median, from the unrounded medians

FIG_SIZE = (20, 11.0)
BAR_WIDTH = 0.36
HEADROOM = 1.1


def build_csv() -> None:
    rows, median = {}, {}
    for target, _, _ in TARGETS:
        for compiler, *_ in COMPILERS:
            for r in target_runs(target, compiler):
                if target == "robot_cpu":
                    inf = r["inference_ms"]
                    stats = [float(inf[k]) for k in ("p50", "p25", "p75")]
                else:
                    calls = agent_computation(r)
                    if not calls:
                        print(f"[warn] {r['run_id']}: no agent profile, skipped")
                        continue
                    q = statistics.quantiles(calls, n=4, method="inclusive")
                    stats = [statistics.median(calls), q[0], q[2]]
                rows[(model_of(r), target, compiler)] = [f"{v:.1f}" for v in stats]  # rounded once, as in exp1
                median[(model_of(r), target, compiler)] = stats[0]
    for (m, t, c), v in rows.items():
        base = median.get((m, t, "aoti"))
        v.append(f"{base / median[(m, t, c)]:.2f}" if c == "sol" and base else "")
    write_rows(CSV, COLUMNS, rows, [(t, c) for t, _, _ in TARGETS for c, *_ in COMPILERS])


# faster compiler of each pair: one highlight, the paper's light green (TEX_COLOUR["edge_gpu"]: the best option in
# Exp. 1, vAccel in Exp. 3), read as "better" -- no new colour
TEX_FASTER = TEX_COLOUR["edge_gpu"]
TEX_CAPTION = ("Exp.~2: Computation time (ms) of models optimized with PyTorch and SOL during local and remote "
               "inference. The better of the two is shaded.")


def write_tex() -> None:
    """exp2-latency.tex (single column) from exp2-latency.csv (medians copied as written): per execution target
    PyTorch (baseline, left) and SOL (right). The speedup is left to the text: PyTorch, SOL and the speedup side
    by side do not fit one column."""
    tasks, raw = read_rows(CSV, 4)
    val = {k: d["inference_ms"] for k, d in raw.items()}
    groups = [(t, title) for t, title, _ in TARGETS]
    order = [("aoti", "PyTorch"), ("sol", "SOL")]  # baseline left, SOL right
    # plain right-aligned columns: every value has one decimal, so they are decimal-aligned anyway, and
    # \cellcolor (the faster compiler's shading) is reliable there, unlike inside siunitx S columns
    spec = "r" * (len(order) * len(groups))
    width, n_cols = len(order), 1 + len(order) * len(groups)

    def cell(m, t, c):
        """Printed value; shaded (one neutral highlight for every target) when it is the faster of the pair
        (printed values; a tie is not shaded)."""
        v = val.get((m, t, c))
        if v is None:
            return "--"
        other = val.get((m, t, "sol" if c == "aoti" else "aoti"))
        faster = other is not None and float(v) < float(other)
        return f"\\cellcolor{{{TEX_FASTER[0]}}}{v}" if faster else v

    lines = ["% Requires: \\usepackage[table]{xcolor}, booktabs",
             "% Generated by exp2_latency.py from exp2-latency.csv -- do not edit by hand."]
    lines += [f"\\definecolor{{{TEX_FASTER[0]}}}{{HTML}}{{{TEX_FASTER[1]}}}"]
    lines += ["\\begin{table}[!t]", f"\\caption{{{TEX_CAPTION}}}", "\\label{tab:exp2-compilers}", "\\centering",
             "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}", f"\\begin{{tabular}}{{@{{}}l{spec}}}", "\\toprule",  # no trailing @{}: last column's shading within the rules
             f" & \\multicolumn{{{n_cols - 1}}}{{c}}{{Computation time (ms)}} \\\\",
             f"\\cmidrule(l){{2-{n_cols}}}",
             " & " + " & ".join(f"\\multicolumn{{{width}}}{{c}}{{{title}}}" for _, title in groups) + " \\\\",
             "".join(f"\\cmidrule({'l' if i == len(groups) - 1 else 'lr'}){{{2 + width * i}-{1 + width * (i + 1)}}}"
                     for i in range(len(groups))),
             "Model & " + " & ".join(f"\\multicolumn{{1}}{{c}}{{{h}}}" for _ in groups for _, h in order) + " \\\\"]
    for task, models in tasks.items():
        lines += ["\\midrule", f"\\multicolumn{{{n_cols}}}{{@{{}}l}}{{\\textit{{{TEX_TASK[task]}}}}} \\\\"]
        for m in models:
            cells = [TEX_INDENT + TEX_MODEL[m]] + [cell(m, t, c) for t, _ in groups for c, _ in order]
            lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    TEX.write_text("\n".join(lines) + "\n")
    print(f"[OK] Saved LaTeX table to: {TEX.name}")


# bar style (this figure and its companion): light fill + darker border of the same hue -- baseline blue,
# ours orange (pale fills; the borders carry the distinction)
BAR_STYLE = {"base": dict(facecolor="#DCE7F3", edgecolor="#2B74B3"), "ours": dict(facecolor="#FCE8D5", edgecolor="#E15726")}
BAR_EDGE_WIDTH = 2.2   # ~0.6-0.8 pt at the printed size
ROLE = {"aoti": "base", "sol": "ours"}


def plot() -> None:
    import matplotlib.patches as mpatches
    tasks, raw = read_rows(CSV, 4)
    values = {k: {c: float(v) for c, v in d.items() if v} for k, d in raw.items()}
    fig = plt.figure(figsize=FIG_SIZE)
    gs = fig.add_gridspec(len(TARGETS), len(tasks), width_ratios=[len(m) for m in tasks.values()],
                          left=0.085, right=0.988, top=0.885, bottom=0.11, wspace=0.2, hspace=0.12)
    for r, (target, row_label, _) in enumerate(TARGETS):
        for col, (task, models) in enumerate(tasks.items()):
            ax = fig.add_subplot(gs[r, col])
            ax.set_ylim(0, max(d["iqr_high_ms"] for (m, t, _), d in values.items()
                               if t == target and m in models) * HEADROOM)
            for j, (compiler, _, _, _) in enumerate(COMPILERS):
                style = BAR_STYLE[ROLE[compiler]]
                for i, m in enumerate(models):
                    d = values.get((m, target, compiler))
                    if d is None:
                        continue
                    x, v = i + (j - 0.5) * BAR_WIDTH, d["inference_ms"]
                    ax.bar(x, v, width=BAR_WIDTH, linewidth=BAR_EDGE_WIDTH, zorder=3, **style)
                    ax.errorbar(x, v, yerr=[[v - d["iqr_low_ms"]], [d["iqr_high_ms"] - v]], fmt="none",
                                ecolor=EDGE_COLOR, elinewidth=2.2, capsize=5, capthick=2.2, zorder=10)
            style_axes(ax, clean=True)
            ax.yaxis.set_major_locator(MaxNLocator(nbins=4))
            ax.set_xlim(-0.5, len(models) - 0.5)
            if r == len(TARGETS) - 1:
                model_ticks(ax, models)
            else:
                ax.set_xticks(range(len(models)))
                ax.set_xticklabels([])
            if r == 0:
                ax.set_title(TITLES.get(task, task))
            if col == 0:
                ax.set_ylabel(row_label)
    fig.text(0.008, 0.5, "Computation time (ms)", rotation=90, ha="center", va="center",
             fontsize=plt.rcParams["axes.labelsize"])
    handles = [mpatches.Patch(linewidth=BAR_EDGE_WIDTH, label=lbl, **BAR_STYLE[ROLE[c]]) for c, lbl, _, _ in COMPILERS]
    fig.legend(handles=handles, loc="lower center", bbox_to_anchor=(0.54, 0.925), ncol=len(COMPILERS),
               **LEGEND_STYLE)
    save(fig, PDF)


DUMBBELL_PDF = HERE / "exp2-latency-dumbbell.pdf"
DUMBBELL_SIZE = (20, 6.6)
DUMBBELL_OFFSET = 0.24  # x offset of the three execution targets around each model


def plot_dumbbell() -> None:
    """Same numbers as exp2-latency.tex in one log-scale panel: per model and execution target a vertical
    segment from the PyTorch time (hollow marker) to the SOL time (filled marker); colour = execution target
    (Exp. 1 colours; Local CPU in the palette's medium blue so its markers stay visible); task separators."""
    import matplotlib.lines as mlines
    tasks, raw = read_rows(CSV, 4)
    val = {k: float(d["inference_ms"]) for k, d in raw.items()}
    color = {t: c for t, _, c in TARGETS}
    color["robot_cpu"] = "#3A7CA5"  # the palette's medium blue: the light Local CPU blue is invisible as a marker
    fig, ax = plt.subplots(figsize=DUMBBELL_SIZE)
    x, ticks, labels, bounds = 0, [], [], []
    for task, models in tasks.items():
        start = x
        for m in models:
            for j, (t, _, _) in enumerate(TARGETS):
                ptc, sol = val.get((m, t, "aoti")), val.get((m, t, "sol"))
                if ptc is None or sol is None:
                    continue
                xx = x + (j - 1) * DUMBBELL_OFFSET
                ax.plot([xx, xx], [ptc, sol], color=color[t], linewidth=2.2, zorder=2)
                ax.plot(xx, ptc, marker="o", markersize=10, markerfacecolor="white", markeredgecolor=color[t],
                        markeredgewidth=2.2, linestyle="none", zorder=3)
                ax.plot(xx, sol, marker="o", markersize=10, color=color[t], markeredgecolor=EDGE_COLOR,
                        markeredgewidth=0.8, linestyle="none", zorder=4)
            ticks.append(x); labels.append(m); x += 1
        bounds.append((start, x - 1, task))
        x += 0.6  # gap between tasks
    ax.set_yscale("log")
    style_axes(ax)
    ax.set_xticks(ticks)
    ax.set_xticklabels([MODEL_NAME.get(m, m) for m in labels], rotation=20, ha="right", rotation_mode="anchor")
    ax.set_xlim(-0.6, x - 0.6 - 0.4)
    for i, (a, b, task) in enumerate(bounds):
        ax.text((a + b) / 2, 1.02, TITLES.get(task, task), transform=ax.get_xaxis_transform(), ha="center",
                va="bottom", fontsize=plt.rcParams["axes.titlesize"])
        if i:
            ax.axvline(a - 0.8, color="#BBBBBB", linewidth=1, zorder=1)
    ax.set_ylabel("Computation time (ms, log)")
    fig.subplots_adjust(left=0.065, right=0.99, top=0.78, bottom=0.2)
    handles = patches([(lbl, color[t]) for t, lbl, _ in TARGETS]) + [
        mlines.Line2D([], [], marker="o", markersize=10, markerfacecolor="white", markeredgecolor=EDGE_COLOR,
                      markeredgewidth=2, linestyle="none", label="PyTorch"),
        mlines.Line2D([], [], marker="o", markersize=10, color=EDGE_COLOR, linestyle="none", label="SOL")]
    fig.legend(handles=handles, loc="lower center", bbox_to_anchor=(0.53, 0.89), ncol=len(handles), **LEGEND_STYLE)
    save(fig, DUMBBELL_PDF)


if __name__ == "__main__":
    build_csv()
    write_tex()
    apply_theme()
    plot()
    plot_dumbbell()
